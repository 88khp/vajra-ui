#!/usr/bin/env node
/**
 * Compiles the Tamagui card with Tamagui's own compiler, the way a Metro build does.
 *
 * Tamagui 3 has no standalone Babel plugin. Its compiler runs inside
 * @tamagui/metro-plugin: a frontend plans every module, then a transformer applies the
 * plan and runs the project's Babel transformer over the lowered source. This script
 * drives those two pieces directly, with the same withTamagui() options an app would
 * use, and writes the result to implementations/tamagui-compiled/benchmark-card.js.
 * Jest then loads that file, so the timed code is exactly what Metro would ship.
 *
 * Usage: node scripts/compile-tamagui.js [--platform ios]
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT, 'implementations/tamagui/benchmark-card.tsx');
const OUT_DIR = path.join(ROOT, 'implementations/tamagui-compiled');
const OUT = path.join(OUT_DIR, 'benchmark-card.js');

const platformArg = process.argv.indexOf('--platform');
const PLATFORM = platformArg > -1 ? process.argv[platformArg + 1] : 'ios';

const main = async () => {
  process.env.NODE_ENV = 'production';
  const { getDefaultConfig } = require('@react-native/metro-config');
  const { withTamagui, getMetroCompilerFrontend } = require('@tamagui/metro-plugin');
  const { createMetroCompilerTransformer } = require('@tamagui/metro-plugin/transformer');

  const cacheBaseRoot = path.join(ROOT, 'node_modules/.cache/tamagui-compiled');
  fs.rmSync(cacheBaseRoot, { recursive: true, force: true });

  const config = withTamagui(getDefaultConfig(ROOT), {
    components: ['tamagui'],
    config: './implementations/tamagui/config.ts',
    compilerCacheRoot: cacheBaseRoot,
  });
  const frontend = getMetroCompilerFrontend(config);
  if (!frontend) throw new Error('withTamagui did not install the compiler frontend');

  const scanOptions = { dev: false, hot: false, platform: PLATFORM, entryFiles: [SOURCE] };
  const generation = await frontend.scan(scanOptions);
  for (const d of generation.diagnostics) console.warn('[tamagui diagnostic]', JSON.stringify(d));

  const transformer = createMetroCompilerTransformer({
    cacheBaseRoot,
    originalBabelTransformerPath: require.resolve('@react-native/metro-babel-transformer', {
      paths: [ROOT],
    }),
    projectRoot: ROOT,
    runtimeLiteral: 'full',
  });
  const result = await transformer.transform({
    filename: SOURCE,
    src: fs.readFileSync(SOURCE, 'utf8'),
    options: {
      dev: false,
      hot: false,
      platform: PLATFORM,
      projectRoot: ROOT,
      enableBabelRCLookup: true,
      enableBabelRuntime: false,
      publicPath: '/assets',
      globalPrefix: '',
      unstable_transformProfile: 'default',
      experimentalImportSupport: false,
      inlineRequires: false,
      minify: false,
      type: 'module',
    },
    plugins: [],
  });

  const meta = result.metadata?.tamagui ?? result.metadata;
  const lowering = meta?.lowering;
  console.log('[tamagui] lowering:', JSON.stringify(lowering ?? meta, null, 2));
  if (!lowering?.applied) {
    throw new Error('Tamagui compiler did not lower the card; refusing to write a "compiled" build');
  }

  const generate = require('@babel/generator').default;
  // The output lives in a sibling folder at the same depth, so only the card's own
  // local import (./config) needs to point back at implementations/tamagui/.
  const code = generate(result.ast, { comments: true }).code.replace(
    /require\("\.\/config"\)/g,
    'require("../tamagui/config")',
  );
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(
    OUT,
    `/* Generated by scripts/compile-tamagui.js from ../tamagui/benchmark-card.tsx. Do not edit. */\n${code}\n`,
  );
  console.log(`[tamagui] wrote ${path.relative(ROOT, OUT)}`);
  await frontend.close();
};

main().catch(err => {
  console.error(err);
  process.exit(1);
});
